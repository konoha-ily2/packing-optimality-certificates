def den(x):
    a, b = x.v
    return math.lcm(a.denominator, b.denominator)


def dens(xs):
    return math.lcm(*[den(x) for x in xs]) if xs else 1


def z5(x, scale):
    a, b = (c * scale for c in x.v)
    need(a.denominator == 1 and b.denominator == 1, "does not become an integer")
    return f"⟨{a.numerator}, {b.numerator}⟩"


def vec(u, scale):
    return "[" + ", ".join(z5(x, scale) for x in u) + "]"


def find_planes(S, pieces):
    """Same search as d87_dod_step0.part_a (face normals → cross products of edge directions). For each pair i < j, (normal, the side of i is smaller)."""
    Vs = [[vadd(mvec(p["R"], u), p["t"]) for u in S.KV] for p in pieces]
    normals = lambda p: [mvec(p["R"], f[0]) for f in S.KF]
    edges_K = sorted({tuple(sorted(e)) for f in S.KF for e in itertools.combinations(f[2], 2)
                      if dot(vsub(S.KV[e[0]], S.KV[e[1]]), vsub(S.KV[e[0]], S.KV[e[1]])) == 1})
    out = {}
    for i, j in itertools.combinations(range(13), 2):
        found = None
        for nrm in normals(pieces[i]) + normals(pieces[j]):
            for sg in (1, -1):
                nn = vscale(sg, nrm)
                if max(dot(nn, x) for x in Vs[i]) <= min(dot(nn, x) for x in Vs[j]):
                    found = nn; break
            if found:
                break
        if found is None:
            for e1 in edges_K:
                d1 = mvec(pieces[i]["R"], vsub(S.KV[e1[1]], S.KV[e1[0]]))
                for e2 in edges_K:
                    d2 = mvec(pieces[j]["R"], vsub(S.KV[e2[1]], S.KV[e2[0]]))
                    nrm = cross(d1, d2)
                    if all(x == 0 for x in nrm):
                        continue
                    for sg in (1, -1):
                        nn = vscale(sg, nrm)
                        if max(dot(nn, x) for x in Vs[i]) <= min(dot(nn, x) for x in Vs[j]):
                            found = nn; break
                    if found:
                        break
                if found:
                    break
        need(found is not None, f"pair ({i}, {j})")
        out[(i, j)] = found
    return out


