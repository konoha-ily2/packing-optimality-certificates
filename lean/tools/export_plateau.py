#
# Reads verifier/ (code), which reads the configurations from certificates/plateau_<case>_n<N>.json. Writes (lean/PackLean/Plateau/, or --out):
#   Data.lean   … 6 Prob values (coordinates as integers a, b of (a + b√d)/L, normals scaled by a positive integer to integer triples, heights in units of 1/L)
#   Ico.lean, Oct.lean … theorems (decide +kernel by default, native_decide with --native)
#   Axioms.lean … #print axioms
#   Test/*.lean … versions with injected errors (--inject). Each must fail in Lean
# Usage (from the repository root):
#   python -X utf8 lean/tools/export_plateau.py --inject              # n = 2, 3, 4
#   python -X utf8 lean/tools/export_plateau.py --inject --n5         # n = 5 (N5Data, N5, N5Axioms, Test/N5*.lean)
#   add --out <dir> to write somewhere else (for comparing with lean/PackLean/Plateau/)
