from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.dirname(HERE)
ROOT = os.path.dirname(LEAN)
OUT = os.path.join(LEAN, "PackLean", "Plateau")
sys.path.insert(0, os.path.join(ROOT, "verifier"))
import d28_plateau_n34 as D28
import d31_plateau_n34 as D31

ap = argparse.ArgumentParser()
ap.add_argument("--native", action="store_true", help="native_decide instead of decide +kernel")
ap.add_argument("--inject", action="store_true", help="write the versions with injected errors to Test/")
ap.add_argument("--build", nargs="*", default=None, help="lake build these modules one at a time")
ap.add_argument("--n5", action="store_true",
                help="write only N5Data, N5, N5Axioms and Test/N5*.lean of the upper bound for n=5 (plateau_n05_upper.py) (Q53; the other files are not written)")
ap.add_argument("--out", default=None, help="output directory instead of lean/PackLean/Plateau")
args = ap.parse_args()
if args.out:
    OUT = os.path.abspath(args.out)
TAC = "native_decide" if args.native else "decide +kernel"


def lcm(a, b): return a * b // math.gcd(a, b)


def comps(x):
    return (x.a, x.b)


def scale_case(raw):
    """Take the common denominator L of the coordinates and make integer pairs. Normals are scaled by a positive integer, heights are in units of 1/L (times the scale of the normal)."""
    L = 1
    for P in raw["pieces"]:
        for pt in P:
            for c in pt:
                for f in comps(c):
                    L = lcm(L, f.denominator)
    pieces = [[tuple((c.a * L, c.b * L) for c in pt) for pt in P] for P in raw["pieces"]]
    for P in pieces:
        for pt in P:
            for a, b in pt:
                assert a.denominator == 1 and b.denominator == 1
    planes = []
    for i, j, nv, h in raw["planes"]:
        m = 1
        for c in nv:
            for f in comps(c):
                m = lcm(m, f.denominator)
        nvi = tuple((c.a * m, c.b * m) for c in nv)
        hi = (h.a * m * L, h.b * m * L)
        for f in list(sum(nvi, ())) + list(hi):
            assert Fr(f).denominator == 1
        planes.append((i, j, nvi, hi))
    return L, pieces, planes


def qd(t): return f"⟨{int(t[0])}, {int(t[1])}⟩"
def v3(p): return f"⟨{qd(p[0])}, {qd(p[1])}, {qd(p[2])}⟩"


def prob_lean(name, d, L, pieces, planes, doc):
    ps = ",\n    ".join("[" + ", ".join(v3(p) for p in P) + "]" for P in pieces)
    pl = ",\n    ".join(f"⟨{i}, {j}, {v3(nv)}, {qd(h)}⟩" for i, j, nv, h in planes)
    return (f"/-- {doc} -/\ndef {name} : Prob where\n  d := {d}\n  L := {L}\n"
            f"  pieces := [\n    {ps}]\n  planes := [\n    {pl}]\n")


HEAD = "-- Generated by lean/tools/export_plateau.py. Do not edit by hand.\n"
# (d, standard solid, sden, cnum, cden, description)
KIND = {"ico": (5, "icoStd", 4, (5, 2), 5, "icointet, container c* = (5 + 2√5)/5 (s*² = 72/5 + 32√5/5)"),
        "oct": (2, "octStd", 2, (0, 3), 4, "octintet, container c = 3√2/4 (s = 3)")}

cases = {}
for n in (2, 3, 4):
    D28.check(n)
    D31.check(n)
    cases[("ico", n)] = scale_case(D28.RAW[n])
    cases[("oct", n)] = scale_case(D31.RAW[n])
# the Python counts (containment inequalities, contacts, planes)
expect = {}
for n in (2, 3, 4):
    for k, mod in (("ico", D28), ("oct", D31)):
        r = mod.check(n)
        expect[(k, n)] = (r["containment_inequalities"], r["wall_contacts"], len(r["separating_planes"]))


def write(path, text):
    if args.n5 and not os.path.basename(path).startswith("N5"):
        return                     # with --n5, do not touch the files for n = 2 to 4
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path) and open(path, encoding="utf8").read() == text:
        return
    open(path, "w", encoding="utf8", newline="\n").write(text)


data = HEAD + "import PackLean.Plateau.Core\n\nnamespace PackLean.Plateau\n\n"
for (k, n), (L, pieces, planes) in sorted(cases.items()):
    d = KIND[k][0]
    data += prob_lean(f"{k}N{n}", d, L, pieces, planes, f"{KIND[k][5]}, n={n}") + "\n"
data += "end PackLean.Plateau\n"
write(os.path.join(OUT, "Data.lean"), data)


def thm(k, n, cnum=None, cden=None, pname=None, tname=None):
    d, std, sden, cn, cd, _ = KIND[k]
    cnum = cnum or cn; cden = cden or cd
    pname = pname or f"{k}N{n}"; tname = tname or f"{k}_n{n}_ok"
    e = expect[(k, n)]
    return (f"theorem {tname} : check {pname} {std} {sden} ⟨{cnum[0]}, {cnum[1]}⟩ {cden} {n} = some ({e[0]}, {e[1]}, {e[2]}) := by\n"
            f"  {TAC}\n\n")


for k in ("ico", "oct"):
    d, std, sden, cn, cd, doc = KIND[k]
    t = HEAD + "import PackLean.Plateau.Data\n\nnamespace PackLean.Plateau\n\n"
    t += f"-- {doc}\n\n"
    if k == "ico":
        t += ("/-- Standard icosahedron (×4): 30 of the 66 pairs are edges (distance² 16 = 4²·1), the others are longer than an edge. -/\n"
              f"theorem ico_std_ok : icoStd.length = 12 ∧ countEq 5 icoStd ⟨16, 0⟩ = 30 ∧ minOk 5 icoStd ⟨16, 0⟩ = true := by\n  {TAC}\n\n"
              "/-- 8c*² = s*²: 8·((5 + 2√5)/5)² = (72 + 32√5)/5. -/\n"
              f"theorem ico_c_ok : (QD.mul 5 ⟨5, 2⟩ ⟨5, 2⟩).smul (8 * 5) = (⟨72, 32⟩ : QD).smul 25 := by\n  {TAC}\n\n")
    else:
        t += ("/-- Standard octahedron (×2): 12 of the 15 pairs are edges (distance² 4 = 2²·1), the others are longer than an edge. -/\n"
              f"theorem oct_std_ok : octStd.length = 6 ∧ countEq 2 octStd ⟨4, 0⟩ = 12 ∧ minOk 2 octStd ⟨4, 0⟩ = true := by\n  {TAC}\n\n"
              "/-- 8c² = 9 (edge 3): 8·(3√2/4)² = 9. -/\n"
              f"theorem oct_c_ok : (QD.mul 2 ⟨0, 3⟩ ⟨0, 3⟩).smul 8 = (⟨9, 0⟩ : QD).smul 16 := by\n  {TAC}\n\n")
    for n in (2, 3, 4):
        t += thm(k, n)
    t += "end PackLean.Plateau\n"
    write(os.path.join(OUT, f"{k.capitalize()}.lean"), t)

ax = ("-- #print axioms (generated)\nimport PackLean.Plateau.Ico\nimport PackLean.Plateau.Oct\n\nopen PackLean.Plateau\n\n"
      + "".join(f"#print axioms {k}_{w}_ok\n" for k in ("ico", "oct") for w in ("std", "c", "n2", "n3", "n4")))
write(os.path.join(OUT, "Axioms.lean"), ax)

if args.inject:
    # versions with injected errors (n = 3, 4, icointet and octintet):
    #   cont … container smaller by 1/1000 (cnum/cden − 1/1000)
    #   vert … move x of vertex 0 of piece 0 by 1/L
    #   plane … height of the first pair raised 1 unit above the minimum of n·P over the vertices of piece j
    for k in ("ico", "oct"):
        d, std, sden, cn, cd, _ = KIND[k]
        for n in (3, 4):
            L, pieces, planes = cases[(k, n)]
            base = HEAD + "import PackLean.Plateau.Data\n\nnamespace PackLean.Plateau.Test\nopen PackLean.Plateau\n\n"
            # cont
            c2 = (cn[0] * 1000 - cd, cn[1] * 1000)
            t = base + f"-- error: container smaller by 1/1000\n" + thm(k, n, cnum=c2, cden=cd * 1000, tname=f"bad_{k}_n{n}_cont") + "end PackLean.Plateau.Test\n"
            write(os.path.join(OUT, "Test", f"{k.capitalize()}N{n}Cont.lean"), t)
            # vert
            bp = [list(P) for P in pieces]
            x = bp[0][0]; bp[0][0] = ((x[0][0] + 1, x[0][1]), x[1], x[2])
            t = (base + "-- error: x of vertex 0 of piece 0 moved by 1/L\n"
                 + prob_lean("bad", d, L, bp, planes, "version with an error") + "\n"
                 + thm(k, n, pname="bad", tname=f"bad_{k}_n{n}_vert") + "end PackLean.Plateau.Test\n")
            write(os.path.join(OUT, "Test", f"{k.capitalize()}N{n}Vert.lean"), t)
            # plane
            mod = D28 if k == "ico" else D31
            i, j, nvi, hi = planes[0]
            F = D28.Q5 if k == "ico" else D31.Q2

            def dotq(nv, p):          # n·P of the vertices of piece j (integer pairs, units of 1/L) in the field
                return mod.dot(tuple(F(a, b) for a, b in nv), tuple(F(a, b) for a, b in p))
            vals = [dotq(nvi, p) for p in pieces[j]]
            lo = vals[0]
            for z in vals[1:]:
                if z <= lo: lo = z
            assert lo.a.denominator == 1 and lo.b.denominator == 1
            bpl = [(i, j, nvi, (lo.a + 1, lo.b))] + planes[1:]
            t = (base + "-- error: height of the separating plane of the first pair raised 1/L above the lowest vertex of piece j\n"
                 + prob_lean("bad", d, L, pieces, bpl, "version with an error") + "\n"
                 + thm(k, n, pname="bad", tname=f"bad_{k}_n{n}_plane") + "end PackLean.Plateau.Test\n")
            write(os.path.join(OUT, "Test", f"{k.capitalize()}N{n}Plane.lean"), t)

if args.n5:
    # Q53: upper bound for n=5. As in plateau_n05_upper.py, only c of the container is replaced by the lower bound value of Q49, then check(5).
    #   icointet: c = (15 + 5√5)/12, octintet: c = 5√2/6.
    # plateau_n05_upper widens the candidate denominators of the rounding (DENS), so it is imported after n = 2 to 4 are done.
    import plateau_n05_upper as U
    assert U.I is D28 and U.O is D31
    K5 = {"ico": ((15, 5), 12, U.C_ICO, D28), "oct": ((0, 5), 6, U.C_OCT, D31)}
    for k, (cn5, cd5, cval, mod) in K5.items():
        assert mod.Q5(Fr(cn5[0], cd5), Fr(cn5[1], cd5)) == cval if k == "ico" else mod.Q2(Fr(cn5[0], cd5), Fr(cn5[1], cd5)) == cval
        mod.CSTAR = cval
        r = mod.check(5)
        cases[(k, 5)] = scale_case(mod.RAW[5])
        expect[(k, 5)] = (r["containment_inequalities"], r["wall_contacts"], len(r["separating_planes"]))

    def thm5(k, cnum=None, cden=None, pname=None, tname=None):
        d, std, sden, _, _, _ = KIND[k]
        cn5, cd5 = K5[k][0], K5[k][1]
        cnum = cnum or cn5; cden = cden or cd5
        pname = pname or f"{k}N5"; tname = tname or f"{k}_n5_ok"
        e = expect[(k, 5)]
        return (f"theorem {tname} : check {pname} {std} {sden} ⟨{cnum[0]}, {cnum[1]}⟩ {cden} 5 = some ({e[0]}, {e[1]}, {e[2]}) := by\n"
                f"  {TAC}\n\n")

    doc5 = {"ico": "icointet, n=5, container c = (15 + 5√5)/12 (s = 5√(3√5+7)/3, s² = 175/9 + (25/3)√5)",
            "oct": "octintet, n=5, container c = 5√2/6 (s = 10/3)"}
    data = HEAD + "import PackLean.Plateau.Core\n\nnamespace PackLean.Plateau\n\n"
    for k in ("ico", "oct"):
        L, pieces, planes = cases[(k, 5)]
        data += prob_lean(f"{k}N5", KIND[k][0], L, pieces, planes, doc5[k]) + "\n"
    data += "end PackLean.Plateau\n"
    write(os.path.join(OUT, "N5Data.lean"), data)

    t = HEAD + "import PackLean.Plateau.N5Data\n\nnamespace PackLean.Plateau\n\n"
    t += ("-- upper bound for n=5 (verifier/plateau_n05_upper.py). The container edge is exactly the lower bound value of Q49.\n\n"
          "/-- icointet: 8c² = s²: 8·((15 + 5√5)/12)² = (175 + 75√5)/9. -/\n"
          f"theorem ico_n5_c_ok : (QD.mul 5 ⟨15, 5⟩ ⟨15, 5⟩).smul (8 * 9) = (⟨175, 75⟩ : QD).smul 144 := by\n  {TAC}\n\n"
          "/-- octintet: 8c² = s² = 100/9: 8·(5√2/6)² = 100/9. -/\n"
          f"theorem oct_n5_c_ok : (QD.mul 2 ⟨0, 5⟩ ⟨0, 5⟩).smul (8 * 9) = (⟨100, 0⟩ : QD).smul 36 := by\n  {TAC}\n\n")
    for k in ("ico", "oct"):
        t += f"/-- {doc5[k]} -/\n" + thm5(k)
    t += "end PackLean.Plateau\n"
    write(os.path.join(OUT, "N5.lean"), t)

    write(os.path.join(OUT, "N5Axioms.lean"),
          "-- #print axioms (generated)\nimport PackLean.Plateau.N5\nimport PackLean.Plateau.N5End\n\n"
          "open PackLean.Plateau\nopen PackLean.Plateau.End\n\n"
          + "".join(f"#print axioms {x}\n" for x in
                    ("ico_n5_c_ok", "oct_n5_c_ok", "ico_n5_ok", "oct_n5_ok",
                     "tv_edges_ok", "cells_ok", "coef_ok", "inrad_tet_ok", "inrad_ico_ok", "inrad_oct_ok",
                     "oct_lb_gt_plateau", "ico_lb_gt_plateau", "oct_lb_eq_n5", "ico_lb_eq_n5")))

    if args.inject:
        # versions with injected errors (n=5): container smaller by 1/1000, x of vertex 0 of piece 0 moved by 1/L, plane of the first pair raised by 1/L
        for k in ("ico", "oct"):
            d = KIND[k][0]
            cn5, cd5, _, mod = K5[k]
            L, pieces, planes = cases[(k, 5)]
            base = HEAD + "import PackLean.Plateau.N5Data\n\nnamespace PackLean.Plateau.Test\nopen PackLean.Plateau\n\n"
            K = k.capitalize()
            c2 = (cn5[0] * 1000 - cd5, cn5[1] * 1000)
            write(os.path.join(OUT, "Test", f"N5{K}Cont.lean"),
                  base + "-- error: container smaller by 1/1000\n" + thm5(k, cnum=c2, cden=cd5 * 1000, tname=f"bad_{k}_n5_cont")
                  + "end PackLean.Plateau.Test\n")
            bp = [list(P) for P in pieces]
            x = bp[0][0]; bp[0][0] = ((x[0][0] + 1, x[0][1]), x[1], x[2])
            write(os.path.join(OUT, "Test", f"N5{K}Vert.lean"),
                  base + "-- error: x of vertex 0 of piece 0 moved by 1/L\n" + prob_lean("bad", d, L, bp, planes, "version with an error") + "\n"
                  + thm5(k, pname="bad", tname=f"bad_{k}_n5_vert") + "end PackLean.Plateau.Test\n")
            i, j, nvi, hi = planes[0]
            F = D28.Q5 if k == "ico" else D31.Q2
            vals = [mod.dot(tuple(F(a, b) for a, b in nvi), tuple(F(a, b) for a, b in p)) for p in pieces[j]]
            lo = vals[0]
            for z in vals[1:]:
                if z <= lo: lo = z
            assert lo.a.denominator == 1 and lo.b.denominator == 1
            bpl = [(i, j, nvi, (lo.a + 1, lo.b))] + planes[1:]
            write(os.path.join(OUT, "Test", f"N5{K}Plane.lean"),
                  base + "-- error: height of the separating plane of the first pair raised 1/L above the lowest vertex of piece j\n"
                  + prob_lean("bad", d, L, pieces, bpl, "version with an error") + "\n"
                  + thm5(k, pname="bad", tname=f"bad_{k}_n5_plane") + "end PackLean.Plateau.Test\n")

for (k, n), (L, pieces, planes) in sorted(cases.items()):
    print(f"{k} n={n}: L={L}, {len(pieces)} pieces, {len(planes)} planes, expected {expect[(k, n)]}")

if args.build is not None:
    BELOW = 0x00004000
    for m in args.build:
        t0 = time.time()
        p = subprocess.run(["lake", "build", m], cwd=LEAN, capture_output=True, text=True, encoding="utf8",
                           errors="replace", creationflags=BELOW)
        dt = time.time() - t0
        tail = "\n".join((p.stdout + p.stderr).strip().splitlines()[-6:])
        print(f"== {m}: {'passed' if p.returncode == 0 else 'failed'} ({dt:.1f} s)\n{tail}", flush=True)
